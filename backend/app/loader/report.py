"""Write docs/DATA_LOAD_REPORT.md: a reconciliation of one load, readable by a human (§10 layer 2).

It answers "what came in, what did we do to it, and why" per file and per trap. Generated
by `python -m app.loader.run`; never edited by hand. Output is sorted, so two runs on the
same files differ only in the header (time, run id).
"""

from __future__ import annotations

from collections import Counter, defaultdict
from datetime import datetime

from app.config.business_rules import BusinessRules
from app.loader.types import LoadResult
from app.loader.write import WriteSummary

# Short names for each trap, matching docs/DATA_AUDIT.md.
TRAP_TITLES: dict[str, str] = {
    "T01": "Two nights in the on-hand file",
    "T02": "Malformed item codes",
    "T03": "Duplicate item rows",
    "T04": "Status is free text",
    "T05": "Legacy ZZ items",
    "T06": "Quietly dead items",
    "T07": "Fresh items",
    "T08": "Category casing",
    "T09": "Pack size is free text",
    "T10": "Mixed units (cases vs pounds)",
    "T11": "Hold and damaged locations",
    "T12": "Zero-quantity split lots",
    "T13": "Negative adjustment lines",
    "T14": "Expired lots",
    "T15": "The six-month line",
    "T16": "Transfers recorded as sales",
    "T17": "Samples recorded as $0 orders",
    "T18": "Credits recorded as negative sales",
    "T19": "Cancelled sales",
    "T20": "Cruise line one-off",
    "T21": "Mixed date formats",
    "T22": "Open orders are committed stock",
    "T23": "Censored demand (stockouts)",
    "T24": "Duplicate PO lines",
    "T25": "PO statuses and partial receipts",
    "T26": "Stale PO dates",
    "T27": "Vendor lead time problems",
    "T28": "Vendor table oddities",
    "T29": "Price list quirks",
    "T30": "Received date is not age",
    "T31": "Lots disappear between nights",
}


def render_report(
    result: LoadResult,
    rules: BusinessRules,
    generated_at: datetime,
    git_sha: str,
    summary: WriteSummary | None,
) -> str:
    d = result.dataset
    run_label = f"#{summary.load_run_id}" if summary else "dry run (nothing written to the database)"
    lines: list[str] = [
        "# Data load report",
        "",
        f"> Generated by `python -m app.loader.run` on {generated_at:%Y-%m-%d %H:%M} UTC.",
        "> Don't edit by hand: re-run the loader."
        " Rules and reasons for every trap are in [DATA_AUDIT.md](DATA_AUDIT.md).",
        "",
        "| | |",
        "|---|---|",
        f"| Load run | {run_label} |",
        f"| Business date (AS_OF) | {rules.as_of_date} |",
        f"| Latest on-hand snapshot used | {d.snapshot_date} |",
        f"| Code version | `{git_sha}` |",
        f"| Business rules fingerprint | `{rules.fingerprint()}` |",
        f"| Data issues logged | {len(result.issues):,} "
        f"({sum(1 for i in result.issues if i.severity == 'error')} errors) |",
        "",
        "## Files: what came in and what happened to it",
        "",
        "Rows read = data lines in the file (header not counted). "
        "Stored = rows that became a clean-table row. "
        "Sales lines are all stored with their demand class, so the drill-down can show them; for sales, "
        "*excluded* means left out of demand, not deleted.",
        "",
        "| File | SHA-256 | Rows read | Stored | Excluded | Corrected | Flagged |",
        "|---|---|--:|--:|--:|--:|--:|",
    ]
    for s in sorted(result.file_stats, key=lambda x: x.file_name):
        a = s.issues_by_action
        lines.append(
            f"| `{s.file_name}` | `{s.sha256[:12]}…` | {s.rows_read:,} | {s.rows_stored:,} | "
            f"{a.get('excluded', 0):,} | {a.get('corrected', 0):,} | {a.get('flagged', 0):,} |"
        )

    lifecycle = Counter(i.lifecycle_status for i in d.items)
    dormant = sorted(i.item_code for i in d.items if i.lifecycle_status == "dormant")
    demand = Counter(s.demand_class for s in d.sales)
    po_status = Counter(p.status for p in d.po_lines)
    lots_by_location = Counter(lot.location_code for lot in d.lots)
    lines += [
        "",
        "## What the clean layer contains",
        "",
        f"- **Items:** {len(d.items)}. "
        + ", ".join(f"{k} {v}" for k, v in sorted(lifecycle.items()))
        + (f" (dormant: {', '.join(dormant)})" if dormant else ""),
        "- **Item code aliases:** " + ", ".join(f"`{a.alias_code!r}` → {a.item_code}" for a in d.aliases),
        f"- **On-hand lots (latest snapshot):** {len(d.lots)}. "
        + ", ".join(f"{k} {v}" for k, v in sorted(lots_by_location.items())),
        f"- **Sales lines:** {len(d.sales):,}. " + ", ".join(f"{k} {v:,}" for k, v in sorted(demand.items())),
        f"- **Purchase order lines:** {len(d.po_lines)}. "
        + ", ".join(f"{k} {v}" for k, v in sorted(po_status.items())),
        f"- **Vendors:** {len(d.vendors)}. **Customers:** {len(d.customers)}. **Prices:** {len(d.prices)} "
        "(phase 2, unused). **Stockout windows:** "
        f"{len(d.stockout_periods)}. **Excluded orders:** {len(d.excluded_orders)}.",
    ]
    if summary:
        lines += [
            f"- **Raw rows stored for this run:** {summary.raw_rows:,} "
            "(every CSV line, exactly as exported).",
            "- **Dana's lead times (vendor_settings):** "
            + (
                f"seeded {', '.join(summary.vendor_settings_seeded)}"
                if summary.vendor_settings_seeded
                else "none seeded"
            )
            + "; "
            + (
                f"kept existing {', '.join(summary.vendor_settings_kept)} untouched"
                if summary.vendor_settings_kept
                else "no existing rows"
            )
            + ". The loader never overwrites her edits.",
            "- **Reconciliation:** database row counts match the pipeline for every clean table: "
            + ", ".join(f"{k} {v:,}" for k, v in summary.clean_rows.items())
            + ".",
        ]

    grouped: dict[tuple[str, str, str, str], list[str]] = defaultdict(list)
    for issue in result.issues:
        grouped[(issue.trap_id or "—", issue.rule_code, issue.severity, issue.action)].append(issue.message)
    lines += [
        "",
        "## Issues by trap",
        "",
        "| Trap | What | Rule | Severity | Action | Rows | Example |",
        "|---|---|---|---|---|--:|---|",
    ]
    for (trap, rule, severity, action), messages in sorted(grouped.items()):
        example = messages[0].replace("|", "\\|")
        lines.append(
            f"| {trap} | {TRAP_TITLES.get(trap, 'Row error')} | `{rule}` | {severity} | {action} | "
            f"{len(messages):,} | {example} |"
        )

    errors = [i for i in result.issues if i.severity == "error"]
    lines += ["", "## Errors", ""]
    if errors:
        for i in errors:
            where = f"{i.source.file} line {i.source.line}" if i.source else "general"
            lines.append(f"- {where}: {i.message}")
    else:
        lines.append("None. Every row was either loaded, or excluded/corrected by a documented rule.")
    lines.append("")
    return "\n".join(lines)
